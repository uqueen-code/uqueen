// Monster emotions
const MONSTER_EMOTIONS = [
  { emoji: '😤', name: '愤怒', animation: 'shake' },
  { emoji: '😢', name: '悲伤', animation: 'bounce' },
  { emoji: '😰', name: '焦虑', animation: 'pulse' },
  { emoji: '😡', name: '烦躁', animation: 'shake' },
  { emoji: '😞', name: '失落', animation: 'bounce' },
  { emoji: '🤯', name: '压力', animation: 'pulse' },
  { emoji: '😒', name: '不满', animation: 'shake' },
  { emoji: '😩', name: '疲惫', animation: 'bounce' },
];

const MONSTER_NAMES = ['小郁闷', '愁愁', '烦烦怪', '闷闷兽', '坏情绪', '糟心虫', '乌云怪', '小烦恼'];

export function usePsychology() {
  const [moodLogs, setMoodLogs] = useState<MoodLog[]>([]);
  const [emotionEntries, setEmotionEntries] = useState<EmotionMonsterEntry[]>([]);
  const [isLoading, setIsLoading] = useState(true);

  const user = useAuthStore((s) => s.user);
  const addToSyncQueue = useOfflineStore((s) => s.addToSyncQueue);

  const userId = user?.id ?? PLACEHOLDER_USER_ID;
  const today = getTodayString();
  const dayIdx = Math.floor((Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 86400000);
  const psychTip = PSYCH_KNOWLEDGE[dayIdx % PSYCH_KNOWLEDGE.length]!;

  const loadData = useCallback(async () => {
    setIsLoading(true);
    try {
      const db = getDatabase();
      const [moods, emotions] = await Promise.all([
        db.moodLogs.where('userId').equals(userId).reverse().limit(60).toArray(),
        db.emotionEntries.where('userId').equals(userId).filter(e => e.date === today).toArray(),
      ]);
      setMoodLogs(moods.map(m => ({
        id: m.id, userId: m.userId, date: m.date, rating: m.rating,
        note: m.note, createdAt: m.createdAt,
      })));
      setEmotionEntries(emotions.map(e => ({
        id: e.id, userId: e.userId, date: e.date, emotion: e.emotion,
        eaten: e.eaten, createdAt: e.createdAt,
      })));
    } catch { /* */ }
    finally { setIsLoading(false); }
  }, [userId, today]);

  useEffect(() => { loadData(); }, [loadData]);

  const todayMood = moodLogs.find(m => m.date === today) ?? null;
  const todayEmotions = emotionEntries.filter(e => e.date === today);
  const monsterName = MONSTER_NAMES[dayIdx % MONSTER_NAMES.length]!;

  // Log mood rating
  const logMood = useCallback(async (rating: number, note?: string) => {
    const id = crypto.randomUUID?.() ?? `mood_${Date.now()}`;
    const log: MoodLog = {
      id, userId, date: today, rating,
      note: note?.trim() || null, createdAt: new Date().toISOString(),
    };
    const db = getDatabase();
    await db.moodLogs.put({ ...log, _synced: false, _modifiedAt: Date.now() });
    addToSyncQueue({ table: 'mood_logs', operation: 'insert', recordId: id, data: log as unknown as Record<string, unknown> });
    setMoodLogs(prev => {
      const filtered = prev.filter(m => m.date !== today);
      return [log, ...filtered];
    });
    return log;
  }, [userId, today, addToSyncQueue]);

  // Feed emotion to monster
  const feedEmotion = useCallback(async (emotion: string) => {
    const id = crypto.randomUUID?.() ?? `emo_${Date.now()}`;
    const entry: EmotionMonsterEntry = {
      id, userId, date: today, emotion, eaten: true,
      createdAt: new Date().toISOString(),
    };
    const db = getDatabase();
    await db.emotionEntries.put({ ...entry, _synced: false, _modifiedAt: Date.now() });
    addToSyncQueue({ table: 'emotion_entries', operation: 'insert', recordId: id, data: entry as unknown as Record<string, unknown> });
    setEmotionEntries(prev => [...prev, entry]);
    return entry;
  }, [userId, today, addToSyncQueue]);

  // Recent mood history (last 7 days)
  const recentMoods = moodLogs.slice(0, 7).reverse();

  return {
    moodLogs, emotionEntries, todayMood, todayEmotions, recentMoods,
    psychTip, monsterName, MONSTER_EMOTIONS,
    isLoading, logMood, feedEmotion, refresh: loadData,
  };
}
